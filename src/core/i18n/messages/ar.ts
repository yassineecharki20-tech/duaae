/**
 * DUAA — Arabic messages (source of truth for the key set).
 *
 * `fr.ts` and `en.ts` are typed as `Record<MessageKey, string>` against this
 * file, so a missing or renamed translation is a compile error, not a runtime
 * surprise. Keys are namespaced by surface (`home.*`, `settings.*`, …) and
 * shared vocabulary lives under `common.*`.
 *
 * Interpolation uses `{name}` placeholders — see `interpolate()` in
 * `src/core/i18n/state.ts`. Pluralisable strings carry CLDR sub-keys
 * (`common.days.few`, `common.days.one`, …) resolved by `translatePlural()`;
 * the base key doubles as the `other` form, and a language that has no such
 * sub-key simply falls back to it.
 *
 * SCOPE NOTE (docs/CONTENT-POLICY.md): religious text — dua bodies, Qur'anic
 * verses, dhikr phrases, traditional dua titles, documented virtues and source
 * citations — stays in Arabic in every language. Translating scripture would be
 * an interpretation, and this product does not publish interpretations. What is
 * translated here is the interface: navigation, labels, settings, dialogs,
 * empty states, errors and accessibility names.
 */

