/** CLDR plural categories. Arabic uses all six; French and English use two. */
export type PluralForm = 'zero' | 'one' | 'two' | 'few' | 'many' | 'other';

type EveryArabicKey = keyof typeof ar;

/**
 * Plural sub-keys (`common.days.few`, …). They are *optional* per language:
 * a catalog without a form falls back to its base key, then to Arabic.
 */
export type PluralMessageKey = {
  [K in EveryArabicKey]: K extends `${string}.${PluralForm}` ? K : never;
}[EveryArabicKey];

/** Keys every catalog must provide — a missing one is a compile error. */
export type MessageKey = Exclude<EveryArabicKey, PluralMessageKey>;

/** Any key accepted by `t()`, plural sub-keys included. */
export type AnyMessageKey = MessageKey | PluralMessageKey;

export type MessageCatalog = Record<MessageKey, string> &
  Partial<Record<PluralMessageKey, string>>;
